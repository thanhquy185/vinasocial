CREATE TABLE stories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(10) UNIQUE NOT NULL,
    user_id INTEGER NOT NULL,
    media_id VARCHAR(24) NOT NULL,
    created_at VARCHAR(19) NOT NULL,
    expired_at VARCHAR(19) NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'ACTIVE',
    moderation_status VARCHAR(8) NOT NULL DEFAULT 'NONE'
);

CREATE INDEX idx_stories_user ON stories(user_id);
CREATE INDEX idx_stories_created_at ON stories(created_at);
CREATE INDEX idx_stories_expired_at ON stories(expired_at);
CREATE INDEX idx_stories_status ON stories(status);
CREATE INDEX idx_stories_moderation_status ON stories(moderation_status);
CREATE INDEX idx_stories_feed ON stories(status, moderation_status, expired_at, created_at);

CREATE TABLE story_stats (
    story_id INTEGER PRIMARY KEY,
    view_count INTEGER NOT NULL DEFAULT 0,
    reply_count INTEGER NOT NULL DEFAULT 0,
    share_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_story_stats_story FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE
);

CREATE TABLE story_settings (
    story_id INTEGER PRIMARY KEY,
    visibility VARCHAR(12) NOT NULL DEFAULT 'EVERYONE',
    allow_like BOOLEAN NOT NULL DEFAULT TRUE,
    allow_reply BOOLEAN NOT NULL DEFAULT TRUE,
    allow_share BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_story_settings_story FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE
);
