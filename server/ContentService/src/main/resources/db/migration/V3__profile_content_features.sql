CREATE TABLE post_tagged_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    CONSTRAINT fk_post_tagged_users_post FOREIGN KEY (post_id) REFERENCES posts(id) ON DELETE CASCADE,
    CONSTRAINT uq_post_tagged_users UNIQUE (post_id, user_id)
);

CREATE INDEX idx_post_tagged_users_user ON post_tagged_users(user_id);

CREATE TABLE story_highlights (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    title VARCHAR(30) NOT NULL,
    created_at VARCHAR(19) NOT NULL
);

CREATE INDEX idx_story_highlights_user ON story_highlights(user_id);

CREATE TABLE story_highlight_stories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    highlight_id INTEGER NOT NULL,
    story_id INTEGER NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT fk_story_highlight_stories_highlight FOREIGN KEY (highlight_id) REFERENCES story_highlights(id) ON DELETE CASCADE,
    CONSTRAINT fk_story_highlight_stories_story FOREIGN KEY (story_id) REFERENCES stories(id) ON DELETE CASCADE,
    CONSTRAINT uq_story_highlight_position UNIQUE (highlight_id, sort_order),
    CONSTRAINT uq_story_highlight_story UNIQUE (highlight_id, story_id)
);

CREATE INDEX idx_story_highlight_stories_story ON story_highlight_stories(story_id);
