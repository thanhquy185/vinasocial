CREATE TABLE posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(10) UNIQUE NOT NULL,
    user_id INTEGER NOT NULL,
    created_at VARCHAR(19) NOT NULL,
    type VARCHAR(7) NOT NULL,
    caption TEXT NOT NULL,
    moderation_status VARCHAR(8) NOT NULL,
    status VARCHAR(8) NOT NULL
);

CREATE TABLE post_stats (
    post_id INTEGER PRIMARY KEY,
    view_count INTEGER NOT NULL,
    like_count INTEGER NOT NULL,
    comment_count INTEGER NOT NULL,
    reup_count INTEGER NOT NULL,
    share_count INTEGER NOT NULL,
    save_count INTEGER NOT NULL,

    CONSTRAINT fk_post_stats_post FOREIGN KEY (post_id) REFERENCES posts(id)
);

CREATE TABLE post_settings (
    post_id INTEGER PRIMARY KEY,
    privacy VARCHAR(12) NOT NULL,
    is_pinned BOOLEAN NOT NULL,
    allow_comment BOOLEAN NOT NULL,
    allow_reup BOOLEAN NOT NULL,
    allow_share BOOLEAN NOT NULL,
    allow_save BOOLEAN NOT NULL,
    show_view_count BOOLEAN NOT NULL,
    show_like_count BOOLEAN NOT NULL,
    show_comment_count BOOLEAN NOT NULL,
    show_reup_count BOOLEAN NOT NULL,
    show_share_count BOOLEAN NOT NULL,
    show_save_count BOOLEAN NOT NULL,

    CONSTRAINT fk_post_settings_post FOREIGN KEY (post_id) REFERENCES posts(id)
);

CREATE TABLE post_medias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id VARCHAR(24) NOT NULL,
    post_id INTEGER NOT NULL,
    CONSTRAINT fk_post_medias_post FOREIGN KEY (post_id) REFERENCES posts(id)
);